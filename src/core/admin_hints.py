def tri(prefix: str, text: str) -> dict[str, str]:
    return {f"{prefix}_{lang}": text for lang in ("uk", "en", "fr")}


def _merge(*parts: dict[str, str]) -> dict[str, str]:
    merged: dict[str, str] = {}
    for part in parts:
        merged.update(part)
    return merged


def seo_hint(name: str) -> str:
    if name.startswith("seo_title"):
        return SEO_TITLE
    if name.startswith("seo_description"):
        return SEO_DESCRIPTION
    return ""


def apply_hints(formfield, name: str, mapping: dict[str, str] | None = None, *, seo: bool = False):
    if formfield is None:
        return None
    text = mapping.get(name, "") if mapping else ""
    if not text and seo:
        text = seo_hint(name)
    if text:
        formfield.help_text = text
    return formfield


